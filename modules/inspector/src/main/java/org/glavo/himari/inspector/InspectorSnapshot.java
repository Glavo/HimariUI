    /// Returns whether `json` names a producer-process handle or ambient font object.
    ///
    /// Matching is case-insensitive and uses substring search so both canonical keys
    /// and accidental producer dumps are rejected.
    ///
    /// @param json the document
    /// @return `true` when a rejected token is present
    private static boolean namesProducerHandle(String json) {
        String lower = json.toLowerCase();
        for (String token : PRODUCER_HANDLE_TOKENS) {
            if (lower.contains(token)) {
                return true;
            }
        }
        return false;
    }

